// Run on a fresh study page: agent-browser eval --stdin < docs/design/d6/verify-avatars.js
(async () => {
  const passed=[];
  const assert=(label,value)=>{if(!value)throw new Error(label);passed.push(label)};
  const get=selector=>document.querySelector(selector);
  const click=selector=>{const e=get(selector);if(!e)throw new Error(`Missing ${selector}`);e.focus();e.click()};
  const fill=(selector,value)=>{get(selector).value=value;get(selector).dispatchEvent(new Event('input',{bubbles:true}))};
  const coreRow=()=>get('[data-person="OpenBot"]');
  const avatar=()=>coreRow().firstElementChild.innerHTML;
  const original=avatar();
  fill('#message','Keep my draft through a rename.');
  click('#profile');
  assert('Core exposes editable name and role',get('#profile-name').value==='OpenBot'&&get('#profile-role').value==='Personal assistant');
  click('#regenerate-avatars');
  const choices=()=>[...document.querySelectorAll('.avatar-choice')];
  assert('Six distinct generated choices',choices().length===6&&new Set(choices().map(e=>e.innerHTML)).size===6);
  assert('Generated choices vary silhouette',new Set(choices().map(e=>e.querySelector('svg>g').innerHTML)).size>=3);
  const firstSet=choices().map(e=>e.innerHTML).join('');
  click('#regenerate-avatars');
  assert('Another set changes choices',choices().map(e=>e.innerHTML).join('')!==firstSet);
  click('.avatar-choice');
  const picked=get('#avatar-stage').innerHTML;
  assert('Selection previews a different avatar',picked!==original);
  assert('Choice exposes selected state',get('.avatar-choice').getAttribute('aria-pressed')==='true');
  assert('Avatar not applied before save',avatar()===original);
  fill('#profile-name','Nova');
  click('#close-dialog-secondary');
  assert('Cancel preserves name and avatar',coreRow().querySelector('strong').textContent==='OpenBot'&&avatar()===original);
  click('#profile');
  fill('#profile-name','Nova');
  fill('#profile-role','Everyday thinking partner');
  click('#regenerate-avatars');click('.avatar-choice');
  const saved=get('#avatar-stage').innerHTML;
  click('#save-instructions');
  assert('Save updates roster identity',coreRow().querySelector('strong').textContent==='Nova'&&avatar()===saved);
  assert('Save updates header and author',get('.header-name').textContent==='Nova'&&get('.author').textContent.includes('Nova'));
  assert('Core retains unique star after rename',!!get('.header-name .personal-star')&&document.querySelectorAll('.sidebar .personal-star').length===1);
  assert('Profile save retains conversation draft',get('#message').value==='Keep my draft through a rename.');
  click('#more');
  assert('Renamed Core cannot be deleted or hidden',!get('#delete-preview')&&!get('#dialog').textContent.includes('Hide Bot'));
  click('#close-dialog');click('#profile');
  assert('Role remains saved',get('#profile-role').value==='Everyday thinking partner');
  fill('#profile-name','A very long custom Bot name with plenty of words to test its width');click('#save-instructions');
  assert('Long name keeps header actions within viewport',get('#more').getBoundingClientRect().right<=innerWidth);
  assert('Long name retains visible Core star',get('.header-name .personal-star').getBoundingClientRect().right<get('#profile').getBoundingClientRect().left);
  click('#profile');fill('#profile-name','Nova <b>');fill('#profile-role','Research');click('#save-instructions');
  assert('Name and role edits keep selected avatar',avatar()===saved);
  assert('Name renders as plain text',get('.header-name').textContent==='Nova <b>'&&!get('.header-name b'));
  click('#profile');fill('#profile-name','   ');click('#save-instructions');
  assert('Blank name is rejected',get('#dialog').open&&document.activeElement.id==='profile-name');
  click('#close-dialog-secondary');click('#search-open');fill('#search-query','Nova');
  assert('Search finds renamed Bot',get('[data-search-person="OpenBot"] strong').textContent==='Nova <b>');
  click('[data-search-person="OpenBot"]');
  assert('Search preserves renamed Core identity',!!get('.header-name .personal-star'));
  click('[data-person="Atlas"]');click('#profile');fill('#profile-name','OpenBot');click('#save-instructions');
  assert('Specialist can share an old display name without gaining star',get('.header-name').textContent==='OpenBot'&&!get('.header-name .personal-star'));
  click('#more');assert('Specialist remains deletable after rename',!!get('#delete-preview'));click('#delete-preview');
  assert('Delete confirmation uses current display name',get('#dialog-title').textContent==='Delete OpenBot?');click('#close-dialog');
  click('[data-person="Research team"]');
  assert('Group recipient uses renamed Core display name',get('[data-dialog="recipients"]').textContent.includes('Nova <b>'));
  click('[data-person="OpenBot"]');click('#profile');
  const attachFile=file=>{const transfer=new DataTransfer();transfer.items.add(file);get('#avatar-file').files=transfer.files;get('#avatar-file').dispatchEvent(new Event('change',{bubbles:true}))};
  attachFile(new File(['<svg/>'],'unsupported.svg',{type:'image/svg+xml'}));
  assert('Unsupported avatar type is rejected',get('#avatar-error').textContent.includes('Choose a PNG'));
  const canvas=document.createElement('canvas');canvas.width=32;canvas.height=16;
  canvas.getContext('2d').fillRect(0,0,32,16);
  const blob=await new Promise(resolve=>canvas.toBlob(resolve,'image/png'));
  attachFile(new File([blob],'fixture.png',{type:'image/png'}));
  const deadline=performance.now()+3000;
  while(!get('#avatar-stage img')&&performance.now()<deadline)await new Promise(requestAnimationFrame);
  assert('Local image produces preview',!!get('#avatar-stage img'));
  assert('Image import waits for explicit save',avatar()===saved);
  const imported=get('#avatar-stage img').src;
  click('#save-instructions');
  assert('Saved image replaces roster and header avatars',coreRow().querySelector('img').src===imported&&get('.header-avatar img').src===imported);
  const bitmap=await createImageBitmap(await(await fetch(imported)).blob());
  assert('Image is normalized to square 256 pixels',bitmap.width===256&&bitmap.height===256);bitmap.close();
  click('#profile');
  assert('Saved image reopens in editor',get('#avatar-stage img').src===imported);
  assert('Profile dialog fits viewport width',get('#dialog').getBoundingClientRect().right<=innerWidth&&get('#dialog').getBoundingClientRect().left>=0);
  assert('No page overflow',document.documentElement.scrollWidth<=innerWidth);
  click('#close-dialog-secondary');
  return {passed:passed.length,viewport:[innerWidth,innerHeight],checks:passed};
})()
